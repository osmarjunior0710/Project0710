const CLASSE = 'Psiônico';

export function aplicarListaPsionico(base: Magia[]): Magia[] {
  const nomes = new Set(Object.values(MAGIAS_OFICIAIS_DO_PSIONICO).flat());
  const atualizadas = base.map((m) =>
    nomes.has(m.nome) && !m.classes.includes(CLASSE) ? { ...m, classes: [...m.classes, CLASSE] } : m,
  );
  return [...atualizadas, ...magiasUAPsionico];
}
